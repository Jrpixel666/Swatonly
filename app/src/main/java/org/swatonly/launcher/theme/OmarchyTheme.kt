package org.swatonly.launcher.theme

/**
 * Omarchy themes (themes/<name>/colors.toml) shown next to the manjaro-sway
 * ones. Each palette becomes a manjaro-sway theme.conf and foot-theme.ini, so
 * the launcher, sway and foot all take the same colours.
 */
object OmarchyTheme {
    const val PREFIX = "omarchy:"

    fun isOmarchy(name: String) = name.startsWith(PREFIX)

    fun parseToml(text: String): Map<String, String> {
        val out = LinkedHashMap<String, String>()
        for (line in text.lineSequence()) {
            val t = line.trim()
            val eq = t.indexOf('=')
            if (eq <= 0 || t.startsWith("#") || t.startsWith("[")) continue
            val v = t.substring(eq + 1).trim()
            out[t.substring(0, eq).trim()] = if (v.startsWith("\"")) v.substring(1).substringBefore('"') else v.substringBefore(" #").trim()
        }
        return out
    }

    private fun c(p: Map<String, String>, vararg keys: String): String =
        keys.firstNotNullOfOrNull { p[it]?.takeIf { v -> v.startsWith("#") } } ?: "#888888"

    /** A manjaro-sway theme.conf for this palette (what Tweaks.applyTheme copies into sway). */
    fun themeConf(name: String, p: Map<String, String>): String {
        val light = p["mode"] == "light"
        val bg = c(p, "background")
        val fg = c(p, "foreground")
        val accent = c(p, "accent", "blue")
        val muted = c(p, "muted", "dark_foreground")
        return """
            |# omarchy $name (generated by the Swatonly launcher from colors.toml)
            |set ${'$'}gtk-theme ${if (light) "Adwaita" else "Adwaita-dark"}
            |set ${'$'}icon-theme ${if (light) "Papirus" else "Papirus-Dark"}
            |set ${'$'}gui-font Roboto 11
            |set ${'$'}term-font JetBrainsMono NF
            |set ${'$'}gtk-color-scheme ${if (light) "prefer-light" else "prefer-dark"}
            |set ${'$'}kvantum-theme ${if (light) "KvGnome" else "KvGnomeDark"}
            |set ${'$'}background ${'$'}HOME/.config/sway/generated_background.svg
            |set ${'$'}cursor-theme ${if (light) "phinger-cursors-dark" else "phinger-cursors-light"}
            |set ${'$'}vscode-theme "Default ${if (light) "Light" else "Dark"} Modern"
            |
            |set ${'$'}surface0 ${c(p, "lighter_background", "selection")}
            |set ${'$'}subtext0 ${c(p, "dark_foreground", "muted")}
            |set ${'$'}red ${c(p, "red")}
            |set ${'$'}peach ${c(p, "orange", "yellow")}
            |
            |set ${'$'}color0 ${c(p, "lighter_background", "selection")}
            |set ${'$'}color1 ${c(p, "red")}
            |set ${'$'}color3 ${c(p, "yellow")}
            |set ${'$'}color5 ${c(p, "magenta")}
            |set ${'$'}color6 ${c(p, "cyan")}
            |set ${'$'}color7 ${c(p, "light_foreground", "foreground")}
            |set ${'$'}color8 ${c(p, "red")}
            |set ${'$'}color9 ${c(p, "orange", "bright_red")}
            |set ${'$'}color10 ${c(p, "green")}
            |set ${'$'}color11 ${c(p, "yellow")}
            |set ${'$'}color12 ${c(p, "blue")}
            |set ${'$'}color13 ${c(p, "magenta")}
            |
            |set ${'$'}background-color $bg
            |set ${'$'}text-color $fg
            |set ${'$'}accent-color $accent
            |
            |# target                 title    bg   text  indicator border
            |client.focused           $accent $bg $fg $accent $accent
            |client.focused_inactive  $muted $bg $fg $muted $muted
            |client.unfocused         $muted $bg $fg $muted $muted
            |client.urgent            ${c(p, "red")} $bg ${c(p, "red")} $muted ${c(p, "red")}
            |client.placeholder       $muted $bg $fg $muted $muted
            |client.background        $bg
            |""".trimMargin()
    }

    /** foot-theme.ini for this palette. */
    fun footIni(p: Map<String, String>): String {
        fun h(vararg k: String) = c(p, *k).removePrefix("#")
        val section = if (p["mode"] == "light") "colors-light" else "colors-dark"
        return """
            |[main]
            |initial-color-theme=${if (p["mode"] == "light") "light" else "dark"}
            |
            |[$section]
            |foreground=${h("foreground")}
            |background=${h("background")}
            |regular0=${h("lighter_background", "selection")}
            |regular1=${h("red")}
            |regular2=${h("green")}
            |regular3=${h("yellow")}
            |regular4=${h("blue")}
            |regular5=${h("magenta")}
            |regular6=${h("cyan")}
            |regular7=${h("foreground")}
            |bright0=${h("muted", "dark_foreground")}
            |bright1=${h("bright_red", "red")}
            |bright2=${h("bright_green", "green")}
            |bright3=${h("bright_yellow", "yellow")}
            |bright4=${h("bright_blue", "blue")}
            |bright5=${h("bright_magenta", "magenta")}
            |bright6=${h("bright_cyan", "cyan")}
            |bright7=${h("bright_foreground", "foreground")}
            |""".trimMargin()
    }

    fun toSwayTheme(name: String, toml: String, source: String): SwayTheme {
        val p = parseToml(toml)
        val short = name.removePrefix(PREFIX)
        return SwayTheme.parse(name, themeConf(short, p), footIni(p), null, source)
    }
}
